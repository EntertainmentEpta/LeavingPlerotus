using System.Collections.Generic;
using UnityEngine;
using UnityEngine.UI;
using TMPro;

/// <summary>
/// HUD do Sistema de Cura do Traje do Eptinho.
/// - Cápsulas visíveis em tamanho legível (Cheia / Sintetizando / Vazia).
/// - Suporta dinamicamente 2 ou 3 cápsulas (com upgrade do robô).
/// - Barra de contagem e progresso de síntese (0s a 60s) de alto contraste e fácil leitura.
/// - Exibe taxa de aceleração dinâmica (1.0x Combate, 0.5x Dano, 1.25x Descanso, 1.50x Anomalia).
/// - Informa claramente 15% HP em combate e 30% HP fora de combate / Anomalia.
/// </summary>
public class SuitHealingUI : MonoBehaviour
{
    public static SuitHealingUI Instance { get; private set; }

    [Header("Configurações do Painel")]
    public Vector2 screenPosition = new Vector2(-280f, 168f); // Acima do Dash HUD
    public Vector2 panelSize = new Vector2(380f, 68f);

    [Header("Cores")]
    public Color readyPotionColor = new Color(0.0f, 0.95f, 0.55f, 1.0f);       // Verde Esmeralda Neon
    public Color emptyPotionColor = new Color(0.06f, 0.12f, 0.08f, 0.85f);     // Vidro escuro
    public Color chargingColor = new Color(0.2f, 0.92f, 0.60f, 0.95f);         // Verde Vivo de Síntese
    public Color slowedDamageColor = new Color(1.0f, 0.55f, 0.20f, 0.95f);     // Laranja de dano
    public Color capsuleBorderColor = new Color(0.18f, 0.60f, 0.38f, 0.9f);

    private GameObject autoCanvasObj;
    private Image panelBgImage;
    private Outline panelOutline;
    private TextMeshProUGUI statusText;
    private TextMeshProUGUI subtitleText;
    private TextMeshProUGUI synthTimerText;
    private Image synthBarFillImage;
    private SuitHealingSystem healingSystem;
    private Transform capsulesContainer;

    // Timers de feedback visual
    private float healFeedbackTimer = 0f;
    private float emptyWarningTimer = 0f;

    // Lista dinâmica de cápsulas
    private List<Image> capsuleFills = new List<Image>();
    private List<Image> capsuleBorders = new List<Image>();
    private int currentRenderedMax = -1;

    private void Awake()
    {
        if (Instance != null && Instance != this)
        {
            Destroy(gameObject);
            return;
        }
        Instance = this;
        DontDestroyOnLoad(gameObject);
    }

    private void Start()
    {
        BuildAutoGeneratedCanvas();
    }

    public void TriggerHealFeedback()
    {
        healFeedbackTimer = 0.5f;
    }

    public void FlashEmptyWarning()
    {
        emptyWarningTimer = 1.6f;
    }

    private void Update()
    {
        string currentScene = UnityEngine.SceneManagement.SceneManager.GetActiveScene().name;
        bool inMainMenu = currentScene == "MainMenu" || currentScene == "Menu";
        if (inMainMenu)
        {
            if (autoCanvasObj != null && autoCanvasObj.activeSelf) autoCanvasObj.SetActive(false);
            return;
        }

        if (autoCanvasObj != null && !autoCanvasObj.activeSelf)
        {
            autoCanvasObj.SetActive(true);
        }

        if (healingSystem == null)
        {
            healingSystem = SuitHealingSystem.Instance ?? FindFirstObjectByType<SuitHealingSystem>();
            if (healingSystem == null)
            {
                PlayerHealth ph = FindFirstObjectByType<PlayerHealth>();
                if (ph != null)
                {
                    healingSystem = ph.gameObject.AddComponent<SuitHealingSystem>();
                }
            }
        }

        if (healingSystem == null) return;

        if (healFeedbackTimer > 0f) healFeedbackTimer -= Time.unscaledDeltaTime;
        if (emptyWarningTimer > 0f) emptyWarningTimer -= Time.unscaledDeltaTime;

        int current = healingSystem.currentPotions;
        int max = Mathf.Max(2, healingSystem.maxPotions);
        float synthProgress = healingSystem.SynthesisProgress;
        float elapsed = healingSystem.ElapsedSynthesisTime;

        // Feedback de flash na borda do painel
        if (panelOutline != null)
        {
            if (healFeedbackTimer > 0f)
            {
                panelOutline.effectColor = Color.Lerp(capsuleBorderColor, readyPotionColor, healFeedbackTimer / 0.5f);
            }
            else if (emptyWarningTimer > 0f)
            {
                panelOutline.effectColor = new Color(1f, 0.25f, 0.25f, 0.95f);
            }
            else
            {
                panelOutline.effectColor = capsuleBorderColor;
            }
        }

        // Se maxPotions mudou (ex: upgrade de reservatório), reconstrói as cápsulas
        if (currentRenderedMax != max)
        {
            RebuildCapsules(max);
        }

        // 1. Atualizar visual de cada cápsula
        float pulse = 0.85f + Mathf.PingPong(Time.time * 2.5f, 0.15f);

        for (int i = 0; i < capsuleFills.Count; i++)
        {
            if (capsuleFills[i] == null) continue;

            if (i < current)
            {
                // CÁPSULA PRONTA PARA USO (Cheia verde neon)
                capsuleFills[i].fillAmount = 1f;
                capsuleFills[i].color = readyPotionColor;
                if (i < capsuleBorders.Count && capsuleBorders[i] != null)
                {
                    capsuleBorders[i].color = readyPotionColor * pulse;
                }
            }
            else if (i == current)
            {
                // CÁPSULA ATUALMENTE SINTETIZANDO (Enchendo em tempo real)
                capsuleFills[i].fillAmount = synthProgress;
                capsuleFills[i].color = healingSystem.IsSlowedByDamage ? slowedDamageColor : chargingColor;
                if (i < capsuleBorders.Count && capsuleBorders[i] != null)
                {
                    capsuleBorders[i].color = (healingSystem.IsSlowedByDamage ? slowedDamageColor : chargingColor) * pulse;
                }
            }
            else
            {
                // CÁPSULA VAZIA NA FILA
                capsuleFills[i].fillAmount = 0f;
                capsuleFills[i].color = emptyPotionColor;
                if (i < capsuleBorders.Count && capsuleBorders[i] != null)
                {
                    capsuleBorders[i].color = capsuleBorderColor;
                }
            }
        }

        // 2. Atualizar Barra Horizontal de Síntese
        if (synthBarFillImage != null)
        {
            if (current >= max)
            {
                synthBarFillImage.fillAmount = 1f;
                synthBarFillImage.color = readyPotionColor;
            }
            else
            {
                synthBarFillImage.fillAmount = synthProgress;
                synthBarFillImage.color = healingSystem.IsSlowedByDamage ? slowedDamageColor : chargingColor;
            }
        }

        // 3. Atualizar Textos Informativos
        if (statusText != null)
        {
            string keyHint = $"<color=#FFFFFF>[ <b>{healingSystem.healKey}</b> ]</color>";

            if (emptyWarningTimer > 0f)
            {
                statusText.text = $"<color=#FF5555><b>SEM CÁPSULAS [0/{max}]</b></color> {keyHint}";
            }
            else if (current >= max)
            {
                statusText.text = $"<color=#00FFAA><b>CURA NO TRAJE [{current}/{max}]</b></color> {keyHint}";
            }
            else
            {
                string statusColor = current > 0 ? "#00FFAA" : "#FF7766";
                statusText.text = $"<color={statusColor}><b>CURA NO TRAJE [{current}/{max}]</b></color> {keyHint}";
            }
        }

        if (subtitleText != null)
        {
            if (emptyWarningTimer > 0f)
            {
                subtitleText.text = "<color=#FFAAAA>Aguarde a biossíntese da próxima cápsula!</color>";
            }
            else
            {
                string healPct = healingSystem.isInAnomalyRoom ? "<color=#00FFAA><b>+30% HP</b> [ANOMALIA]</color>" :
                                 (healingSystem.IsInCombat ? "<color=#FFE082><b>+15% HP</b> [COMBATE]</color>" : "<color=#80E89E><b>+30% HP</b> [DESCANSO]</color>");
                subtitleText.text = $"Eficácia: {healPct}  <size=90%><color=#88A090>(Traje: {healingSystem.SuitIntegrityPercent:F0}%)</color></size>";
            }
        }

        if (synthTimerText != null)
        {
            if (current >= max)
            {
                synthTimerText.text = $"<color=#E8F5E9><b>100% CARREGADO • TRAJE ESTÁVEL</b></color>";
            }
            else
            {
                string rateStr = healingSystem.IsSlowedByDamage ? "<color=#FF6644>0.5x [DANO]</color>" : 
                                 (healingSystem.isInAnomalyRoom ? "<color=#00FFAA>1.50x [ANOMALIA]</color>" :
                                 (healingSystem.IsInCombat ? "1.0x" : "<color=#80E89E>1.25x [DESCANSO]</color>"));

                synthTimerText.text = $"Sintetizando #{current + 1}: <b>{elapsed:F0}s / 60s</b> ({synthProgress * 100:F0}%) <size=85%>{rateStr}</size>";
            }
        }
    }

    private void RebuildCapsules(int maxCount)
    {
        currentRenderedMax = maxCount;
        capsuleFills.Clear();
        capsuleBorders.Clear();

        if (capsulesContainer == null) return;

        foreach (Transform child in capsulesContainer)
        {
            Destroy(child.gameObject);
        }

        Sprite pixel = Sprite.Create(Texture2D.whiteTexture, new Rect(0, 0, 1, 1), Vector2.zero);
        float widthPerCap = 1.0f / maxCount;

        for (int i = 0; i < maxCount; i++)
        {
            GameObject capObj = new GameObject($"Capsule_{i}");
            capObj.transform.SetParent(capsulesContainer, false);

            RectTransform capRect = capObj.AddComponent<RectTransform>();
            capRect.anchorMin = new Vector2(i * widthPerCap, 0);
            capRect.anchorMax = new Vector2((i + 1) * widthPerCap, 1);
            capRect.offsetMin = new Vector2(2, 2);
            capRect.offsetMax = new Vector2(-2, -2);

            Image border = capObj.AddComponent<Image>();
            border.sprite = pixel;
            border.color = capsuleBorderColor;
            capsuleBorders.Add(border);

            GameObject bgObj = new GameObject("CapBg");
            bgObj.transform.SetParent(capObj.transform, false);
            RectTransform bgRect = bgObj.AddComponent<RectTransform>();
            bgRect.anchorMin = Vector2.zero;
            bgRect.anchorMax = Vector2.one;
            bgRect.offsetMin = new Vector2(2, 2);
            bgRect.offsetMax = new Vector2(-2, -2);

            Image bg = bgObj.AddComponent<Image>();
            bg.sprite = pixel;
            bg.color = emptyPotionColor;

            GameObject fillObj = new GameObject("CapFill");
            fillObj.transform.SetParent(capObj.transform, false);
            RectTransform fillRect = fillObj.AddComponent<RectTransform>();
            fillRect.anchorMin = Vector2.zero;
            fillRect.anchorMax = Vector2.one;
            fillRect.offsetMin = new Vector2(2, 2);
            fillRect.offsetMax = new Vector2(-2, -2);

            Image fill = fillObj.AddComponent<Image>();
            fill.sprite = pixel;
            fill.type = Image.Type.Filled;
            fill.fillMethod = Image.FillMethod.Vertical;
            fill.fillOrigin = (int)Image.OriginVertical.Bottom;
            fill.color = readyPotionColor;
            fill.fillAmount = 1f;

            capsuleFills.Add(fill);
        }
    }

    private void BuildAutoGeneratedCanvas()
    {
        if (autoCanvasObj != null) Destroy(autoCanvasObj);

        autoCanvasObj = new GameObject("SuitHealing_CanvasHUD");
        DontDestroyOnLoad(autoCanvasObj);

        Canvas canvas = autoCanvasObj.AddComponent<Canvas>();
        canvas.renderMode = RenderMode.ScreenSpaceOverlay;
        canvas.sortingOrder = 500;

        CanvasScaler scaler = autoCanvasObj.AddComponent<CanvasScaler>();
        scaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
        scaler.referenceResolution = new Vector2(1920, 1080);

        autoCanvasObj.AddComponent<GraphicRaycaster>();

        // Painel Principal
        GameObject panelObj = new GameObject("HealingPanel");
        panelObj.transform.SetParent(autoCanvasObj.transform, false);

        RectTransform panelRect = panelObj.AddComponent<RectTransform>();
        panelRect.anchorMin = new Vector2(1, 0);
        panelRect.anchorMax = new Vector2(1, 0);
        panelRect.pivot = new Vector2(1, 0);
        panelRect.anchoredPosition = screenPosition;
        panelRect.sizeDelta = panelSize;

        panelBgImage = panelObj.AddComponent<Image>();
        panelBgImage.sprite = Sprite.Create(Texture2D.whiteTexture, new Rect(0, 0, 1, 1), Vector2.zero);
        panelBgImage.color = new Color(0.04f, 0.08f, 0.06f, 0.94f);

        panelOutline = panelObj.AddComponent<Outline>();
        panelOutline.effectColor = capsuleBorderColor;
        panelOutline.effectDistance = new Vector2(1.5f, -1.5f);

        Sprite pixel = Sprite.Create(Texture2D.whiteTexture, new Rect(0, 0, 1, 1), Vector2.zero);

        // Container Esquerdo: Cápsulas Verticais
        GameObject capsContainerObj = new GameObject("CapsulesContainer");
        capsContainerObj.transform.SetParent(panelObj.transform, false);
        capsulesContainer = capsContainerObj.transform;

        RectTransform capsRect = capsContainerObj.AddComponent<RectTransform>();
        capsRect.anchorMin = new Vector2(0, 0);
        capsRect.anchorMax = new Vector2(0.18f, 1);
        capsRect.offsetMin = new Vector2(6, 6);
        capsRect.offsetMax = new Vector2(0, -6);

        RebuildCapsules(2);

        // Centro/Direita: Container com 3 Linhas bem legíveis
        GameObject infoContainer = new GameObject("InfoContainer");
        infoContainer.transform.SetParent(panelObj.transform, false);

        RectTransform infoRect = infoContainer.AddComponent<RectTransform>();
        infoRect.anchorMin = new Vector2(0.20f, 0);
        infoRect.anchorMax = new Vector2(1f, 1f);
        infoRect.offsetMin = new Vector2(6, 4);
        infoRect.offsetMax = new Vector2(-6, -4);

        // Linha 1: Título / Status Principal (Fonte 14)
        GameObject textObj = new GameObject("StatusText");
        textObj.transform.SetParent(infoContainer.transform, false);

        RectTransform textRect = textObj.AddComponent<RectTransform>();
        textRect.anchorMin = new Vector2(0, 0.65f);
        textRect.anchorMax = new Vector2(1f, 1f);
        textRect.offsetMin = Vector2.zero;
        textRect.offsetMax = Vector2.zero;

        statusText = textObj.AddComponent<TextMeshProUGUI>();
        statusText.fontSize = 14;
        statusText.fontStyle = FontStyles.Bold;
        statusText.alignment = TextAlignmentOptions.MidlineLeft;
        statusText.color = Color.white;
        statusText.textWrappingMode = TextWrappingModes.NoWrap;

        Shadow textShadow = textObj.AddComponent<Shadow>();
        textShadow.effectColor = new Color(0, 0, 0, 0.95f);
        textShadow.effectDistance = new Vector2(1f, -1f);

        // Linha 2: Subtítulo Explicativo (Eficácia: +30% HP Descanso / +15% HP Combate - Fonte 11)
        GameObject subObj = new GameObject("SubtitleText");
        subObj.transform.SetParent(infoContainer.transform, false);

        RectTransform subRect = subObj.AddComponent<RectTransform>();
        subRect.anchorMin = new Vector2(0, 0.36f);
        subRect.anchorMax = new Vector2(1f, 0.65f);
        subRect.offsetMin = Vector2.zero;
        subRect.offsetMax = Vector2.zero;

        subtitleText = subObj.AddComponent<TextMeshProUGUI>();
        subtitleText.fontSize = 11;
        subtitleText.fontStyle = FontStyles.Normal;
        subtitleText.alignment = TextAlignmentOptions.MidlineLeft;
        subtitleText.color = new Color(0.8f, 0.9f, 0.85f);
        subtitleText.textWrappingMode = TextWrappingModes.NoWrap;

        Shadow subShadow = subObj.AddComponent<Shadow>();
        subShadow.effectColor = new Color(0, 0, 0, 0.9f);
        subShadow.effectDistance = new Vector2(1f, -1f);

        // Linha 3: Barra de Progresso Horizontal de Síntese
        GameObject barBgObj = new GameObject("SynthBarBg");
        barBgObj.transform.SetParent(infoContainer.transform, false);

        RectTransform barBgRect = barBgObj.AddComponent<RectTransform>();
        barBgRect.anchorMin = new Vector2(0, 0);
        barBgRect.anchorMax = new Vector2(1f, 0.35f);
        barBgRect.offsetMin = Vector2.zero;
        barBgRect.offsetMax = Vector2.zero;

        Image barBg = barBgObj.AddComponent<Image>();
        barBg.sprite = pixel;
        barBg.color = new Color(0.06f, 0.12f, 0.08f, 0.90f);

        GameObject barFillObj = new GameObject("SynthBarFill");
        barFillObj.transform.SetParent(barBgObj.transform, false);

        RectTransform barFillRect = barFillObj.AddComponent<RectTransform>();
        barFillRect.anchorMin = Vector2.zero;
        barFillRect.anchorMax = Vector2.one;
        barFillRect.offsetMin = new Vector2(1, 1);
        barFillRect.offsetMax = new Vector2(-1, -1);

        synthBarFillImage = barFillObj.AddComponent<Image>();
        synthBarFillImage.sprite = pixel;
        synthBarFillImage.type = Image.Type.Filled;
        synthBarFillImage.fillMethod = Image.FillMethod.Horizontal;
        synthBarFillImage.fillOrigin = (int)Image.OriginHorizontal.Left;
        synthBarFillImage.color = chargingColor;
        synthBarFillImage.fillAmount = 0.5f;

        // Texto em cima da barra com o Timer (Fonte 12 em negrito)
        GameObject timerObj = new GameObject("TimerText");
        timerObj.transform.SetParent(barBgObj.transform, false);

        RectTransform timerRect = timerObj.AddComponent<RectTransform>();
        timerRect.anchorMin = Vector2.zero;
        timerRect.anchorMax = Vector2.one;
        timerRect.offsetMin = new Vector2(4, 0);
        timerRect.offsetMax = new Vector2(-4, 0);

        synthTimerText = timerObj.AddComponent<TextMeshProUGUI>();
        synthTimerText.fontSize = 12;
        synthTimerText.fontStyle = FontStyles.Bold;
        synthTimerText.alignment = TextAlignmentOptions.Center;
        synthTimerText.color = Color.white;
        synthTimerText.textWrappingMode = TextWrappingModes.NoWrap;

        Shadow timerShadow = timerObj.AddComponent<Shadow>();
        timerShadow.effectColor = new Color(0, 0, 0, 0.95f);
        timerShadow.effectDistance = new Vector2(1f, -1f);
    }
}
