using UnityEngine;
using UnityEngine.UI;
using TMPro;

/// <summary>
/// HUD do Sistema de Cura do Traje do Eptinho (Medidor de Biomassa).
/// - Barra contínua de Biomassa (0% a 100%) com porcentagem atual.
/// - Em 100%: destaque pulsante "PRONTA" indicando que [Q] pode ser usado.
/// - Indicador dinâmico de eficácia: +15% HP [COMBATE] / +30% HP [DESCANSO] / +30% HP [ANOMALIA].
/// </summary>
public class SuitHealingUI : MonoBehaviour
{
    public static SuitHealingUI Instance { get; private set; }

    [Header("Configurações do Painel")]
    public Vector2 screenPosition = new Vector2(-280f, 168f); // Acima do Dash HUD
    public Vector2 panelSize = new Vector2(380f, 68f);

    [Header("Cores")]
    public Color readyColor = new Color(0.0f, 0.95f, 0.55f, 1.0f);             // Verde Esmeralda Neon (100%)
    public Color chargingColor = new Color(0.2f, 0.92f, 0.60f, 0.95f);         // Verde Vivo (acumulando)
    public Color gainFlashColor = new Color(0.75f, 1.0f, 0.85f, 1.0f);         // Brilho ao ganhar biomassa
    public Color perfectDodgeColor = new Color(1.0f, 0.84f, 0.0f, 1.0f);       // Dourado (Esquiva Perfeita)
    public Color panelBorderColor = new Color(0.18f, 0.60f, 0.38f, 0.9f);

    private GameObject autoCanvasObj;
    private Image panelBgImage;
    private Outline panelOutline;
    private TextMeshProUGUI statusText;
    private TextMeshProUGUI subtitleText;
    private TextMeshProUGUI barText;
    private Image barFillImage;
    private SuitHealingSystem healingSystem;

    // Timers de feedback visual
    private float healFeedbackTimer = 0f;
    private float insufficientWarningTimer = 0f;
    private float perfectDodgeAlertTimer = 0f;
    private float gainFlashTimer = 0f;
    private float lastBiomass = 0f;

    private void Awake()
    {
        if (Instance != null && Instance != this)
        {
            Destroy(gameObject);
            return;
        }
        Instance = this;
        DontDestroyOnLoad(gameObject);
    }

    private void Start()
    {
        BuildAutoGeneratedCanvas();
    }

    private void OnDestroy()
    {
        if (Instance == this) Instance = null;
    }

    public void TriggerHealFeedback()
    {
        healFeedbackTimer = 0.5f;
    }

    /// <summary>Alerta de "Biomassa insuficiente" ao apertar [Q] antes dos 100%.</summary>
    public void FlashEmptyWarning()
    {
        insufficientWarningTimer = 1.6f;
    }

    /// <summary>Disparado pelo DashM quando o jogador acerta um Perfect Dash (+35% Biomassa).</summary>
    public void TriggerPerfectDodgeAlert()
    {
        perfectDodgeAlertTimer = 2.0f;
    }

    private void Update()
    {
        if (autoCanvasObj != null)
        {
            CanvasGroup cg = autoCanvasObj.GetComponent<CanvasGroup>();
            if (cg != null)
            {
                bool hideForInventory = (InventoryUI.Instance != null && InventoryUI.Instance.IsOpen()) ||
                                       (SyntheticBagUI.Instance != null && SyntheticBagUI.Instance.IsOpen()) ||
                                       (CraftingUI.Instance != null && CraftingUI.Instance.IsOpen());
                cg.alpha = hideForInventory ? 0f : 1f;
                cg.blocksRaycasts = !hideForInventory;
            }
        }
        string currentScene = UnityEngine.SceneManagement.SceneManager.GetActiveScene().name;
        bool inMainMenu = currentScene == "MainMenu" || currentScene == "Menu";
        if (inMainMenu)
        {
            if (autoCanvasObj != null && autoCanvasObj.activeSelf) autoCanvasObj.SetActive(false);
            return;
        }

        if (autoCanvasObj != null && !autoCanvasObj.activeSelf)
        {
            autoCanvasObj.SetActive(true);
        }

        if (healingSystem == null)
        {
            healingSystem = SuitHealingSystem.Instance ?? FindFirstObjectByType<SuitHealingSystem>();
            if (healingSystem == null)
            {
                PlayerHealth ph = FindFirstObjectByType<PlayerHealth>();
                if (ph != null)
                {
                    healingSystem = ph.gameObject.AddComponent<SuitHealingSystem>();
                }
            }
        }

        if (healingSystem == null) return;

        if (healFeedbackTimer > 0f) healFeedbackTimer -= Time.unscaledDeltaTime;
        if (insufficientWarningTimer > 0f) insufficientWarningTimer -= Time.unscaledDeltaTime;
        if (perfectDodgeAlertTimer > 0f) perfectDodgeAlertTimer -= Time.unscaledDeltaTime;
        if (gainFlashTimer > 0f) gainFlashTimer -= Time.unscaledDeltaTime;

        float biomass = healingSystem.CurrentBiomass;
        if (biomass > lastBiomass + 0.01f) gainFlashTimer = 0.35f;
        lastBiomass = biomass;

        int percent = healingSystem.BiomassPercent;
        bool isFull = healingSystem.IsBiomassFull;
        float readyPulse = 0.5f + 0.5f * Mathf.Sin(Time.unscaledTime * 6f);

        // 1. Borda do painel
        if (panelOutline != null)
        {
            if (healFeedbackTimer > 0f)
            {
                panelOutline.effectColor = Color.Lerp(panelBorderColor, readyColor, healFeedbackTimer / 0.5f);
            }
            else if (perfectDodgeAlertTimer > 0f)
            {
                panelOutline.effectColor = Color.Lerp(perfectDodgeColor, panelBorderColor, 1f - Mathf.Clamp01(perfectDodgeAlertTimer / 2.0f));
            }
            else if (insufficientWarningTimer > 0f)
            {
                panelOutline.effectColor = new Color(1f, 0.25f, 0.25f, 0.95f);
            }
            else if (isFull)
            {
                panelOutline.effectColor = Color.Lerp(panelBorderColor, readyColor, readyPulse);
            }
            else
            {
                panelOutline.effectColor = panelBorderColor;
            }
        }

        // 2. Barra de Biomassa
        if (barFillImage != null)
        {
            barFillImage.fillAmount = healingSystem.BiomassNormalized;
            if (isFull)
            {
                barFillImage.color = Color.Lerp(readyColor, gainFlashColor, readyPulse * 0.6f);
            }
            else if (gainFlashTimer > 0f)
            {
                barFillImage.color = Color.Lerp(chargingColor, gainFlashColor, gainFlashTimer / 0.35f);
            }
            else
            {
                barFillImage.color = chargingColor;
            }
        }

        // 3. Textos
        if (statusText != null)
        {
            string keyHint = $"<color=#FFFFFF>[ <b>{healingSystem.healKey}</b> ]</color>";

            if (insufficientWarningTimer > 0f)
            {
                statusText.text = $"<color=#FF5555><b>BIOMASSA INSUFICIENTE [{percent}%]</b></color> {keyHint}";
            }
            else if (isFull)
            {
                statusText.text = $"<color=#00FFAA><b>CURA NO TRAJE [100%] PRONTA!</b></color> {keyHint}";
            }
            else
            {
                string pctColor = percent >= 50 ? "#00FFAA" : "#FFD27A";
                statusText.text = $"<color={pctColor}><b>CURA NO TRAJE [{percent}%]</b></color> {keyHint}";
            }
        }

        if (subtitleText != null)
        {
            if (perfectDodgeAlertTimer > 0f)
            {
                subtitleText.text = "<color=#FFE082><b>⚡ ESQUIVA PERFEITA! +35% BIOMASSA</b></color>";
            }
            else if (insufficientWarningTimer > 0f)
            {
                subtitleText.text = "<color=#FFAAAA>Acerte golpes, abata inimigos ou esquive no tempo certo!</color>";
            }
            else
            {
                string healPct = healingSystem.isInAnomalyRoom ? "<color=#00FFAA><b>+30% HP</b> [ANOMALIA]</color>" :
                                 (healingSystem.IsInCombat ? "<color=#FFE082><b>+15% HP</b> [COMBATE]</color>" : "<color=#80E89E><b>+30% HP</b> [DESCANSO]</color>");
                subtitleText.text = $"Eficácia: {healPct}  <size=90%><color=#88A090>(Traje: {healingSystem.SuitIntegrityPercent:F0}%)</color></size>";
            }
        }

        if (barText != null)
        {
            if (isFull)
            {
                barText.text = $"<color=#FFFFFF><b>100% • PRONTA PARA USO • [{healingSystem.healKey}]</b></color>";
            }
            else
            {
                barText.text = $"BIOMASSA: <b>{percent}%</b>";
            }
        }
    }

    private void BuildAutoGeneratedCanvas()
    {
        if (autoCanvasObj != null) Destroy(autoCanvasObj);

        autoCanvasObj = new GameObject("SuitHealing_CanvasHUD");
        DontDestroyOnLoad(autoCanvasObj);

        Canvas canvas = autoCanvasObj.AddComponent<Canvas>();
        canvas.renderMode = RenderMode.ScreenSpaceOverlay;
        canvas.sortingOrder = 1;

        CanvasScaler scaler = autoCanvasObj.AddComponent<CanvasScaler>();
        scaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
        scaler.referenceResolution = new Vector2(1920, 1080);

        autoCanvasObj.AddComponent<GraphicRaycaster>();
        autoCanvasObj.AddComponent<CanvasGroup>();

        // Painel Principal
        GameObject panelObj = new GameObject("HealingPanel");
        panelObj.transform.SetParent(autoCanvasObj.transform, false);

        RectTransform panelRect = panelObj.AddComponent<RectTransform>();
        panelRect.anchorMin = new Vector2(1, 0);
        panelRect.anchorMax = new Vector2(1, 0);
        panelRect.pivot = new Vector2(1, 0);
        panelRect.anchoredPosition = screenPosition;
        panelRect.sizeDelta = panelSize;

        Sprite pixel = Sprite.Create(Texture2D.whiteTexture, new Rect(0, 0, 1, 1), Vector2.zero);

        panelBgImage = panelObj.AddComponent<Image>();
        panelBgImage.sprite = pixel;
        panelBgImage.color = new Color(0.04f, 0.08f, 0.06f, 0.94f);

        panelOutline = panelObj.AddComponent<Outline>();
        panelOutline.effectColor = panelBorderColor;
        panelOutline.effectDistance = new Vector2(1.5f, -1.5f);

        // Container com 3 linhas legíveis
        GameObject infoContainer = new GameObject("InfoContainer");
        infoContainer.transform.SetParent(panelObj.transform, false);

        RectTransform infoRect = infoContainer.AddComponent<RectTransform>();
        infoRect.anchorMin = Vector2.zero;
        infoRect.anchorMax = Vector2.one;
        infoRect.offsetMin = new Vector2(8, 4);
        infoRect.offsetMax = new Vector2(-8, -4);

        // Linha 1: Título / Status Principal
        GameObject textObj = new GameObject("StatusText");
        textObj.transform.SetParent(infoContainer.transform, false);

        RectTransform textRect = textObj.AddComponent<RectTransform>();
        textRect.anchorMin = new Vector2(0, 0.65f);
        textRect.anchorMax = new Vector2(1f, 1f);
        textRect.offsetMin = Vector2.zero;
        textRect.offsetMax = Vector2.zero;

        statusText = textObj.AddComponent<TextMeshProUGUI>();
        statusText.fontSize = 14;
        statusText.fontStyle = FontStyles.Bold;
        statusText.alignment = TextAlignmentOptions.MidlineLeft;
        statusText.color = Color.white;
        statusText.textWrappingMode = TextWrappingModes.NoWrap;

        Shadow textShadow = textObj.AddComponent<Shadow>();
        textShadow.effectColor = new Color(0, 0, 0, 0.95f);
        textShadow.effectDistance = new Vector2(1f, -1f);

        // Linha 2: Eficácia (+15% HP [COMBATE] / +30% HP [DESCANSO])
        GameObject subObj = new GameObject("SubtitleText");
        subObj.transform.SetParent(infoContainer.transform, false);

        RectTransform subRect = subObj.AddComponent<RectTransform>();
        subRect.anchorMin = new Vector2(0, 0.36f);
        subRect.anchorMax = new Vector2(1f, 0.65f);
        subRect.offsetMin = Vector2.zero;
        subRect.offsetMax = Vector2.zero;

        subtitleText = subObj.AddComponent<TextMeshProUGUI>();
        subtitleText.fontSize = 11;
        subtitleText.fontStyle = FontStyles.Normal;
        subtitleText.alignment = TextAlignmentOptions.MidlineLeft;
        subtitleText.color = new Color(0.8f, 0.9f, 0.85f);
        subtitleText.textWrappingMode = TextWrappingModes.NoWrap;

        Shadow subShadow = subObj.AddComponent<Shadow>();
        subShadow.effectColor = new Color(0, 0, 0, 0.9f);
        subShadow.effectDistance = new Vector2(1f, -1f);

        // Linha 3: Barra Horizontal de Biomassa
        GameObject barBgObj = new GameObject("BiomassBarBg");
        barBgObj.transform.SetParent(infoContainer.transform, false);

        RectTransform barBgRect = barBgObj.AddComponent<RectTransform>();
        barBgRect.anchorMin = new Vector2(0, 0);
        barBgRect.anchorMax = new Vector2(1f, 0.35f);
        barBgRect.offsetMin = Vector2.zero;
        barBgRect.offsetMax = Vector2.zero;

        Image barBg = barBgObj.AddComponent<Image>();
        barBg.sprite = pixel;
        barBg.color = new Color(0.06f, 0.12f, 0.08f, 0.90f);

        GameObject barFillObj = new GameObject("BiomassBarFill");
        barFillObj.transform.SetParent(barBgObj.transform, false);

        RectTransform barFillRect = barFillObj.AddComponent<RectTransform>();
        barFillRect.anchorMin = Vector2.zero;
        barFillRect.anchorMax = Vector2.one;
        barFillRect.offsetMin = new Vector2(1, 1);
        barFillRect.offsetMax = new Vector2(-1, -1);

        barFillImage = barFillObj.AddComponent<Image>();
        barFillImage.sprite = pixel;
        barFillImage.type = Image.Type.Filled;
        barFillImage.fillMethod = Image.FillMethod.Horizontal;
        barFillImage.fillOrigin = (int)Image.OriginHorizontal.Left;
        barFillImage.color = chargingColor;
        barFillImage.fillAmount = 0f;

        // Texto sobre a barra
        GameObject barTextObj = new GameObject("BiomassText");
        barTextObj.transform.SetParent(barBgObj.transform, false);

        RectTransform barTextRect = barTextObj.AddComponent<RectTransform>();
        barTextRect.anchorMin = Vector2.zero;
        barTextRect.anchorMax = Vector2.one;
        barTextRect.offsetMin = new Vector2(4, 0);
        barTextRect.offsetMax = new Vector2(-4, 0);

        barText = barTextObj.AddComponent<TextMeshProUGUI>();
        barText.fontSize = 12;
        barText.fontStyle = FontStyles.Bold;
        barText.alignment = TextAlignmentOptions.Center;
        barText.color = Color.white;
        barText.textWrappingMode = TextWrappingModes.NoWrap;

        Shadow barShadow = barTextObj.AddComponent<Shadow>();
        barShadow.effectColor = new Color(0, 0, 0, 0.95f);
        barShadow.effectDistance = new Vector2(1f, -1f);
    }
}
