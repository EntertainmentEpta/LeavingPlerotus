using System.Collections.Generic;
using UnityEngine;
using UnityEngine.UI;
using TMPro;

/// <summary>
/// Exibe a UI do Dash no Canvas (HUD) em formato de barras modulares horizontais (uma barra por carga).
/// Suporta qualquer número de cargas (2, 3, 4+ dashes) com recarga individual por barra e efeito de Esquiva Perfeita.
/// </summary>
public class DashUI : MonoBehaviour
{
    public static DashUI Instance { get; private set; }

    [Header("Referências Globais")]
    public DashM dashScript;

    [Header("Configurações da UI Modular (HUD)")]
    public bool useAutoGeneratedUI = true;
    public Vector2 screenPosition = new Vector2(-280f, 115f); // Posicionado acima do Ultimate UI
    public Vector2 panelSize = new Vector2(240f, 38f);         // Barra horizontal elegante

    [Header("Cores dos Estados")]
    public Color readyColor = new Color(0.15f, 0.88f, 1.0f, 1.0f);            // Ciano Neon Brilhante
    public Color rechargeProgressColor = new Color(0.2f, 0.70f, 0.95f, 0.9f); // Azul/Ciano Elétrico de Recarga
    public Color emptySlotColor = new Color(0.10f, 0.14f, 0.18f, 0.85f);       // Fundo escuro do slot
    public Color perfectDodgeColor = new Color(1.0f, 0.84f, 0.0f, 1.0f);       // Dourado Elétrico

    private GameObject autoCanvasObj;
    private RectTransform panelRect;
    private Image panelBgImage;
    private TextMeshProUGUI statusText;
    private Transform barsContainer;

    // Slots modulares de barra (um para cada carga de dash)
    private class BarSlotUI
    {
        public GameObject rootObj;
        public Image bgImage;
        public Image fillImage;
        public Image borderImage;
    }

    private List<BarSlotUI> barSlots = new List<BarSlotUI>();
    private float perfectDodgeFlashTimer = 0f;

    void Awake()
    {
        Instance = this;
    }

    void OnEnable()
    {
        UnityEngine.SceneManagement.SceneManager.sceneLoaded += OnSceneLoaded;
    }

    void OnDisable()
    {
        UnityEngine.SceneManagement.SceneManager.sceneLoaded -= OnSceneLoaded;
    }

    private void OnSceneLoaded(UnityEngine.SceneManagement.Scene scene, UnityEngine.SceneManagement.LoadSceneMode mode)
    {
        if (dashScript == null)
        {
            dashScript = GetComponentInParent<DashM>() ?? GetComponent<DashM>() ?? FindFirstObjectByType<DashM>();
        }

        if (useAutoGeneratedUI && (autoCanvasObj == null || barsContainer == null))
        {
            BuildAutoGeneratedCanvas();
        }
    }

    void Start()
    {
        if (dashScript == null)
        {
            dashScript = GetComponentInParent<DashM>() ?? GetComponent<DashM>() ?? FindFirstObjectByType<DashM>();
        }

        if (useAutoGeneratedUI && (autoCanvasObj == null || barsContainer == null))
        {
            BuildAutoGeneratedCanvas();
        }
    }

    /// <summary>
    /// Chamado pelo DashM quando o jogador realiza um Perfect Dash.
    /// </summary>
    public void TriggerPerfectDodgeFlash()
    {
        perfectDodgeFlashTimer = 1.6f;
    }

    void Update()
    {
        string currentScene = UnityEngine.SceneManagement.SceneManager.GetActiveScene().name;
        bool inMainMenu = currentScene == "MainMenu" || currentScene == "Menu";
        bool isWakingUp = PlayerWakeUpEffect.IsWakingUp;
        bool waitingForIntro = !EptinhoStoryDialogs.HasSeenDialog(EptinhoStoryDialogs.ID_INTRO_EPTINHO);

        if (inMainMenu || isWakingUp || waitingForIntro)
        {
            if (autoCanvasObj != null && autoCanvasObj.activeSelf) autoCanvasObj.SetActive(false);
            return;
        }

        if (autoCanvasObj != null && !autoCanvasObj.activeSelf)
        {
            autoCanvasObj.SetActive(true);
        }

        if (dashScript == null)
        {
            dashScript = GetComponentInParent<DashM>() ?? GetComponent<DashM>() ?? FindFirstObjectByType<DashM>();
        }

        if (useAutoGeneratedUI && (autoCanvasObj == null || barsContainer == null))
        {
            BuildAutoGeneratedCanvas();
        }

        if (dashScript == null) return;

        int maxCharges = Mathf.Max(1, dashScript.MaxDashes);
        int chargesLeft = dashScript.DashesLeft;

        // 1. Sincronização Modular das Barras: recria os slots se maxDashes mudou (ex: upgrades de 2 para 3 dashes)
        if (barSlots.Count != maxCharges && barsContainer != null)
        {
            RebuildBarSlots(maxCharges);
        }

        bool isPerfectDodgeActive = perfectDodgeFlashTimer > 0f;
        if (isPerfectDodgeActive)
        {
            perfectDodgeFlashTimer -= Time.unscaledDeltaTime;
        }

        // 2. Atualiza o preenchimento e cor de CADA barra separadamente
        for (int i = 0; i < barSlots.Count; i++)
        {
            BarSlotUI slot = barSlots[i];
            float progress = dashScript.GetSlotProgress(i);
            bool isReady = dashScript.IsSlotReady(i);

            slot.fillImage.fillAmount = progress;

            if (isPerfectDodgeActive)
            {
                slot.fillImage.fillAmount = 1f;
                slot.fillImage.color = perfectDodgeColor;
                slot.borderImage.color = perfectDodgeColor * (0.8f + Mathf.PingPong(Time.unscaledTime * 6f, 0.2f));
            }
            else if (isReady)
            {
                slot.fillImage.color = readyColor;
                slot.borderImage.color = readyColor * (0.85f + Mathf.PingPong(Time.time * 2f, 0.15f));
            }
            else
            {
                slot.fillImage.color = rechargeProgressColor;
                slot.borderImage.color = new Color(0.2f, 0.35f, 0.5f, 0.6f);
            }
        }

        // 3. Atualizar Texto do Cabeçalho
        if (statusText != null)
        {
            string keyHint = dashScript.dashKey == KeyCode.Space ? "[ ESPAÇO ]" : $"[ ESPAÇO / {dashScript.dashKey} ]";

            if (isPerfectDodgeActive)
            {
                statusText.text = $"<color=#FFD700><b>★ ESQUIVA PERFEITA! ★</b></color> <size=75%><color=#00FFAA>+100% CRÍTICO</color></size>";
            }
            else if (chargesLeft >= maxCharges)
            {
                statusText.text = $"<color=#00E5FF><b>DASH [{chargesLeft}/{maxCharges}]</b></color> <size=75%>{keyHint}</size>";
            }
            else if (chargesLeft > 0)
            {
                float remaining = dashScript.CurrentCooldownTimer;
                statusText.text = $"<color=#00E5FF><b>DASH [{chargesLeft}/{maxCharges}]</b></color> <size=75%><color=#88EEFF>(+{remaining:F1}s)</color> {keyHint}</size>";
            }
            else
            {
                float remaining = dashScript.CurrentCooldownTimer;
                statusText.text = $"<color=#FF7755><b>RECUPERANDO [{remaining:F1}s]</b></color> <size=75%><color=#AAAAAA>{keyHint}</color></size>";
            }
        }
    }

    private void RebuildBarSlots(int count)
    {
        // Limpar slots antigos
        foreach (var slot in barSlots)
        {
            if (slot.rootObj != null) Destroy(slot.rootObj);
        }
        barSlots.Clear();

        Sprite pixelSprite = Sprite.Create(Texture2D.whiteTexture, new Rect(0, 0, 1, 1), Vector2.zero);

        // Cria os novos slots de barra
        for (int i = 0; i < count; i++)
        {
            GameObject slotObj = new GameObject($"DashBar_{i}");
            slotObj.transform.SetParent(barsContainer, false);

            LayoutElement le = slotObj.AddComponent<LayoutElement>();
            le.flexibleWidth = 1f;
            le.minHeight = 12f;

            // Borda / Moldura
            Image border = slotObj.AddComponent<Image>();
            border.sprite = pixelSprite;
            border.color = new Color(0.2f, 0.35f, 0.5f, 0.6f);

            // Fundo escuro do slot
            GameObject bgObj = new GameObject("SlotBg");
            bgObj.transform.SetParent(slotObj.transform, false);
            RectTransform bgRect = bgObj.AddComponent<RectTransform>();
            bgRect.anchorMin = Vector2.zero;
            bgRect.anchorMax = Vector2.one;
            bgRect.offsetMin = new Vector2(1, 1);
            bgRect.offsetMax = new Vector2(-1, -1);

            Image bg = bgObj.AddComponent<Image>();
            bg.sprite = pixelSprite;
            bg.color = emptySlotColor;

            // Fill da Barra (Horizontal da esquerda para a direita)
            GameObject fillObj = new GameObject("SlotFill");
            fillObj.transform.SetParent(slotObj.transform, false);
            RectTransform fillRect = fillObj.AddComponent<RectTransform>();
            fillRect.anchorMin = Vector2.zero;
            fillRect.anchorMax = Vector2.one;
            fillRect.offsetMin = new Vector2(1, 1);
            fillRect.offsetMax = new Vector2(-1, -1);

            Image fill = fillObj.AddComponent<Image>();
            fill.sprite = pixelSprite;
            fill.type = Image.Type.Filled;
            fill.fillMethod = Image.FillMethod.Horizontal;
            fill.fillOrigin = (int)Image.OriginHorizontal.Left;
            fill.color = readyColor;
            fill.fillAmount = 1f;

            barSlots.Add(new BarSlotUI
            {
                rootObj = slotObj,
                bgImage = bg,
                fillImage = fill,
                borderImage = border
            });
        }
    }

    private void BuildAutoGeneratedCanvas()
    {
        if (autoCanvasObj != null) Destroy(autoCanvasObj);

        // 1. Canvas HUD Overlay
        autoCanvasObj = new GameObject("Dash_CanvasHUD");
        DontDestroyOnLoad(autoCanvasObj);

        Canvas canvas = autoCanvasObj.AddComponent<Canvas>();
        canvas.renderMode = RenderMode.ScreenSpaceOverlay;
        canvas.sortingOrder = 95;

        CanvasScaler scaler = autoCanvasObj.AddComponent<CanvasScaler>();
        scaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
        scaler.referenceResolution = new Vector2(1920, 1080);

        autoCanvasObj.AddComponent<GraphicRaycaster>();

        // 2. Painel Principal (Horizontal elegante)
        GameObject panelObj = new GameObject("DashModularPanel");
        panelObj.transform.SetParent(autoCanvasObj.transform, false);

        panelRect = panelObj.AddComponent<RectTransform>();
        panelRect.anchorMin = new Vector2(1, 0);
        panelRect.anchorMax = new Vector2(1, 0);
        panelRect.pivot = new Vector2(1, 0);
        panelRect.anchoredPosition = screenPosition;
        panelRect.sizeDelta = panelSize;

        panelBgImage = panelObj.AddComponent<Image>();
        panelBgImage.sprite = Sprite.Create(Texture2D.whiteTexture, new Rect(0, 0, 1, 1), Vector2.zero);
        panelBgImage.color = new Color(0.04f, 0.07f, 0.10f, 0.88f);

        // 3. Texto de Status / Label
        GameObject textObj = new GameObject("DashStatusText");
        textObj.transform.SetParent(panelObj.transform, false);

        RectTransform textRect = textObj.AddComponent<RectTransform>();
        textRect.anchorMin = new Vector2(0, 0.5f);
        textRect.anchorMax = new Vector2(1, 1f);
        textRect.offsetMin = new Vector2(6, 0);
        textRect.offsetMax = new Vector2(-6, -2);

        statusText = textObj.AddComponent<TextMeshProUGUI>();
        statusText.fontSize = 11;
        statusText.fontStyle = FontStyles.Bold;
        statusText.alignment = TextAlignmentOptions.MidlineLeft;
        statusText.color = Color.white;
        statusText.textWrappingMode = TextWrappingModes.NoWrap;

        Shadow textShadow = textObj.AddComponent<Shadow>();
        textShadow.effectColor = new Color(0, 0, 0, 0.9f);
        textShadow.effectDistance = new Vector2(1f, -1f);

        // 4. Container Horizontal das Barras Modulares
        GameObject containerObj = new GameObject("BarsContainer");
        containerObj.transform.SetParent(panelObj.transform, false);

        RectTransform containerRect = containerObj.AddComponent<RectTransform>();
        containerRect.anchorMin = new Vector2(0, 0);
        containerRect.anchorMax = new Vector2(1, 0.55f);
        containerRect.offsetMin = new Vector2(6, 4);
        containerRect.offsetMax = new Vector2(-6, -1);

        HorizontalLayoutGroup hlg = containerObj.AddComponent<HorizontalLayoutGroup>();
        hlg.padding = new RectOffset(0, 0, 0, 0);
        hlg.spacing = 6f; // Espaçamento elegante entre as barras
        hlg.childControlWidth = true;
        hlg.childControlHeight = true;
        hlg.childForceExpandWidth = true;
        hlg.childForceExpandHeight = true;

        barsContainer = containerObj.transform;

        // Constrói os slots iniciais baseados no DashM
        int initialDashes = (dashScript != null) ? Mathf.Max(1, dashScript.MaxDashes) : 2;
        RebuildBarSlots(initialDashes);
    }
}
