        ocBg.sprite = pixelSprite;
        ocBg.color = emptySlotColor;

        GameObject ocFillObj = new GameObject("OverchargeFill");
        ocFillObj.transform.SetParent(overchargeObj.transform, false);
        RectTransform ocFillRect = ocFillObj.AddComponent<RectTransform>();
        ocFillRect.anchorMin = Vector2.zero;
        ocFillRect.anchorMax = Vector2.one;
        ocFillRect.offsetMin = new Vector2(1, 1);
        ocFillRect.offsetMax = new Vector2(-1, -1);

        overchargeFillImage = ocFillObj.AddComponent<Image>();
        overchargeFillImage.sprite = pixelSprite;
        overchargeFillImage.type = Image.Type.Filled;
        overchargeFillImage.fillMethod = Image.FillMethod.Horizontal;
        overchargeFillImage.fillOrigin = (int)Image.OriginHorizontal.Left;
        overchargeFillImage.color = perfectDodgeColor;
        overchargeFillImage.fillAmount = 0f;

        // Label interno da Sobrecarga
        GameObject ocLabelObj = new GameObject("OverchargeLabel");
        ocLabelObj.transform.SetParent(overchargeObj.transform, false);
        RectTransform ocLabelRect = ocLabelObj.AddComponent<RectTransform>();
        ocLabelRect.anchorMin = Vector2.zero;
        ocLabelRect.anchorMax = Vector2.one;

        overchargeLabelText = ocLabelObj.AddComponent<TextMeshProUGUI>();
        overchargeLabelText.fontSize = 9;
        overchargeLabelText.fontStyle = FontStyles.Bold;
        overchargeLabelText.alignment = TextAlignmentOptions.Center;
        overchargeLabelText.color = Color.white;
        overchargeLabelText.text = "<color=#556677>SOBRECARGA</color>";

        int initialDashes = (dashScript != null) ? Mathf.Max(1, dashScript.MaxDashes) : 2;
        RebuildBarSlots(initialDashes);
    }
}
