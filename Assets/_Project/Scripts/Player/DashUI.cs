using UnityEngine;
using UnityEngine.UI;
using TMPro;

/// <summary>
/// Exibe a UI do Dash no Canvas (HUD), similar ao UltimateUI.
/// Suporta o sistema de cargas independentes (estilo Hades) e feedback de Esquiva Perfeita (Perfect Dash).
/// </summary>
public class DashUI : MonoBehaviour
{
    public static DashUI Instance { get; private set; }

    [Header("Referências Globais")]
    public DashM dashScript;

    [Header("Componentes Manuais de UI (Opcional)")]
    public Image cooldownFillImage;
    public TextMeshProUGUI countdownText;
    public Image statusBorderImage;

    [Header("Configurações da UI Automática (HUD)")]
    public bool useAutoGeneratedUI = true;
    public Vector2 screenPosition = new Vector2(-280f, 115f); // Posicionado logo acima do painel de Ultimate
    public Vector2 panelSize = new Vector2(230f, 62f);

    [Header("Cores dos Estados")]
    public Color readyColor = new Color(0.15f, 0.85f, 1.0f, 1.0f);   // Ciano Neon
    public Color cooldownColor = new Color(1.0f, 0.35f, 0.2f, 1.0f);  // Laranja / Vermelho
    public Color rechargeProgressColor = new Color(0.2f, 0.7f, 0.9f, 1.0f);
    public Color perfectDodgeColor = new Color(1.0f, 0.84f, 0.0f, 1.0f); // Dourado Elétrico

    private GameObject autoCanvasObj;
    private Image autoFillImage;
    private TextMeshProUGUI autoText;
    private Image autoBorderImage;
    private float perfectDodgeFlashTimer = 0f;

    void Awake()
    {
        Instance = this;
    }

    void OnEnable()
    {
        UnityEngine.SceneManagement.SceneManager.sceneLoaded += OnSceneLoaded;
    }

    void OnDisable()
    {
        UnityEngine.SceneManagement.SceneManager.sceneLoaded -= OnSceneLoaded;
    }

    private void OnSceneLoaded(UnityEngine.SceneManagement.Scene scene, UnityEngine.SceneManagement.LoadSceneMode mode)
    {
        if (dashScript == null)
        {
            dashScript = GetComponentInParent<DashM>() ?? GetComponent<DashM>() ?? FindFirstObjectByType<DashM>();
        }

        if (useAutoGeneratedUI && (autoCanvasObj == null || autoFillImage == null))
        {
            BuildAutoGeneratedCanvas();
        }
    }

    void Start()
    {
        if (dashScript == null)
        {
            dashScript = GetComponentInParent<DashM>() ?? GetComponent<DashM>() ?? FindFirstObjectByType<DashM>();
        }

        if ((cooldownFillImage == null || countdownText == null) && useAutoGeneratedUI)
        {
            BuildAutoGeneratedCanvas();
        }
    }

    /// <summary>
    /// Chamado pelo DashM quando o jogador realiza um Perfect Dash.
    /// </summary>
    public void TriggerPerfectDodgeFlash()
    {
        perfectDodgeFlashTimer = 1.6f;
    }

    void Update()
    {
        string currentScene = UnityEngine.SceneManagement.SceneManager.GetActiveScene().name;
        bool inMainMenu = currentScene == "MainMenu" || currentScene == "Menu";
        bool isWakingUp = PlayerWakeUpEffect.IsWakingUp;
        bool waitingForIntro = !EptinhoStoryDialogs.HasSeenDialog(EptinhoStoryDialogs.ID_INTRO_EPTINHO);

        if (inMainMenu || isWakingUp || waitingForIntro)
        {
            if (autoCanvasObj != null && autoCanvasObj.activeSelf) autoCanvasObj.SetActive(false);
            return;
        }

        if (autoCanvasObj != null && !autoCanvasObj.activeSelf)
        {
            autoCanvasObj.SetActive(true);
        }

        if (dashScript == null)
        {
            dashScript = GetComponentInParent<DashM>() ?? GetComponent<DashM>() ?? FindFirstObjectByType<DashM>();
        }

        if (useAutoGeneratedUI && (autoCanvasObj == null || autoFillImage == null))
        {
            BuildAutoGeneratedCanvas();
        }

        if (dashScript == null) return;

        bool isRecharging = dashScript.IsRecharging;
        float remainingSec = dashScript.CurrentCooldownTimer;
        int chargesLeft = dashScript.DashesLeft;
        int maxCharges = Mathf.Max(1, dashScript.MaxDashes);
        float chargeProgress = dashScript.ChargeProgress;

        Image targetFill = cooldownFillImage != null ? cooldownFillImage : autoFillImage;
        TextMeshProUGUI targetText = countdownText != null ? countdownText : autoText;
        Image targetBorder = statusBorderImage != null ? statusBorderImage : autoBorderImage;

        // 1. Efeito de Flash / Destaque de Esquiva Perfeita (Perfect Dash)
        if (perfectDodgeFlashTimer > 0f)
        {
            perfectDodgeFlashTimer -= Time.unscaledDeltaTime;

            if (targetFill != null)
            {
                targetFill.fillAmount = 1f;
                targetFill.color = perfectDodgeColor;
            }

            if (targetBorder != null)
            {
                float pulse = 0.8f + Mathf.PingPong(Time.unscaledTime * 6f, 0.2f);
                targetBorder.color = perfectDodgeColor * pulse;
            }

            if (targetText != null)
            {
                targetText.text = $"<color=#FFD700><b>★ ESQUIVA PERFEITA! ★</b></color>\n<size=75%><color=#00FFAA>+100% CRÍTICO ATIVO</color></size>";
            }
            return;
        }

        // 2. Preenchimento da Barra com Recarga Independente (Hades Style)
        if (targetFill != null)
        {
            if (chargesLeft >= maxCharges)
            {
                targetFill.fillAmount = 1f;
                targetFill.color = readyColor;
            }
            else if (chargesLeft > 0)
            {
                // Mostra as cargas cheias + o progresso fracionado da próxima recarga
                float totalProgress = (chargesLeft + chargeProgress) / (float)maxCharges;
                targetFill.fillAmount = Mathf.Clamp01(totalProgress);
                targetFill.color = readyColor;
            }
            else
            {
                // 0 cargas: barra proporcional à recuperação da 1ª carga
                float singleProgress = chargeProgress / (float)maxCharges;
                targetFill.fillAmount = Mathf.Clamp01(singleProgress);
                targetFill.color = cooldownColor;
            }
        }

        // 3. Atualizar Texto e Indicador de Cargas
        if (targetText != null)
        {
            string keyHint = dashScript.dashKey == KeyCode.Space ? "[ ESPAÇO ]" : $"[ ESPAÇO / {dashScript.dashKey} ]";

            if (chargesLeft >= maxCharges)
            {
                targetText.text = $"<color=#00E5FF><b>DASH [{chargesLeft}/{maxCharges}] PRONTO</b></color>\n<size=75%>{keyHint}</size>";
            }
            else if (chargesLeft > 0)
            {
                targetText.text = $"<color=#00E5FF><b>DASH [{chargesLeft}/{maxCharges}]</b> <size=80%>(+{remainingSec:F1}s)</size></color>\n<size=75%>{keyHint}</size>";
            }
            else
            {
                targetText.text = $"<color=#FF5555><b>RECUPERANDO [{remainingSec:F1}s]</b></color>\n<size=75%><color=#AAAAAA>AGUARDE CARGA</color></size>";
            }
        }

        // 4. Borda do Painel
        if (targetBorder != null)
        {
            if (chargesLeft > 0)
            {
                float pulse = 0.85f + Mathf.PingPong(Time.time * 2f, 0.15f);
                targetBorder.color = readyColor * pulse;
            }
            else
            {
                targetBorder.color = new Color(0.25f, 0.15f, 0.15f, 0.9f);
            }
        }
    }

    private void BuildAutoGeneratedCanvas()
    {
        if (autoCanvasObj != null) Destroy(autoCanvasObj);

        // 1. Criar Canvas Overlay no HUD
        autoCanvasObj = new GameObject("Dash_CanvasHUD");
        DontDestroyOnLoad(autoCanvasObj);

        Canvas canvas = autoCanvasObj.AddComponent<Canvas>();
        canvas.renderMode = RenderMode.ScreenSpaceOverlay;
        canvas.sortingOrder = 95;

        CanvasScaler scaler = autoCanvasObj.AddComponent<CanvasScaler>();
        scaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
        scaler.referenceResolution = new Vector2(1920, 1080);

        autoCanvasObj.AddComponent<GraphicRaycaster>();

        // 2. Criar Painel Principal (Canto Inferior Direito, acima do Ultimate)
        GameObject panelObj = new GameObject("DashPanel");
        panelObj.transform.SetParent(autoCanvasObj.transform, false);

        RectTransform panelRect = panelObj.AddComponent<RectTransform>();
        panelRect.anchorMin = new Vector2(1, 0);
        panelRect.anchorMax = new Vector2(1, 0);
        panelRect.pivot = new Vector2(1, 0);
        panelRect.anchoredPosition = screenPosition;
        panelRect.sizeDelta = panelSize;

        autoBorderImage = panelObj.AddComponent<Image>();
        autoBorderImage.color = new Color(0.08f, 0.12f, 0.16f, 0.88f);

        // 3. Criar Barra de Progresso / Fill Image
        GameObject fillObj = new GameObject("CooldownBarFill");
        fillObj.transform.SetParent(panelObj.transform, false);

        RectTransform fillRect = fillObj.AddComponent<RectTransform>();
        fillRect.anchorMin = Vector2.zero;
        fillRect.anchorMax = Vector2.one;
        fillRect.offsetMin = new Vector2(4, 4);
        fillRect.offsetMax = new Vector2(-4, -4);

        autoFillImage = fillObj.AddComponent<Image>();
        autoFillImage.sprite = Sprite.Create(Texture2D.whiteTexture, new Rect(0, 0, 1, 1), Vector2.zero);
        autoFillImage.type = Image.Type.Filled;
        autoFillImage.fillMethod = Image.FillMethod.Horizontal;
        autoFillImage.fillOrigin = (int)Image.OriginHorizontal.Left;
        autoFillImage.color = readyColor;

        // 4. Criar Texto Numérico do Countdown (TMPro)
        GameObject textObj = new GameObject("CountdownText");
        textObj.transform.SetParent(panelObj.transform, false);

        RectTransform textRect = textObj.AddComponent<RectTransform>();
        textRect.anchorMin = Vector2.zero;
        textRect.anchorMax = Vector2.one;
        textRect.offsetMin = new Vector2(8, 2);
        textRect.offsetMax = new Vector2(-8, -2);

        autoText = textObj.AddComponent<TextMeshProUGUI>();
        autoText.fontSize = 13;
        autoText.fontStyle = FontStyles.Bold;
        autoText.alignment = TextAlignmentOptions.Center;
        autoText.color = Color.white;
        autoText.textWrappingMode = TextWrappingModes.Normal;

        // Efeito de sombra sutil
        Shadow shadow = textObj.AddComponent<Shadow>();
        shadow.effectColor = new Color(0, 0, 0, 0.9f);
        shadow.effectDistance = new Vector2(1.5f, -1.5f);
    }
}
